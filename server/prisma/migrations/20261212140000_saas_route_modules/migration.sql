-- SaaS launch, phase 2.4/section 10: which module each API route belongs to (draft from the SaaS plan, edited on the /platform screen).
-- A request path is matched by the longest path_prefix; a path with no row is not gated. Used only while the "Module access checks" switch is ON and only for
-- customer companies. menu_prefix is the client menu path that disappears when the module is not available.
CREATE TABLE "saas_route_modules" (
    "id" UUID NOT NULL DEFAULT gen_random_uuid(),
    "path_prefix" TEXT NOT NULL,
    "menu_prefix" TEXT,
    "module_code" VARCHAR(8) NOT NULL,
    "note" TEXT,
    "active" BOOLEAN NOT NULL DEFAULT true,
    CONSTRAINT "saas_route_modules_pkey" PRIMARY KEY ("id")
);
CREATE UNIQUE INDEX "saas_route_modules_path_prefix_key" ON "saas_route_modules"("path_prefix");
CREATE INDEX "saas_route_modules_module_code_idx" ON "saas_route_modules"("module_code");
ALTER TABLE "saas_route_modules" ADD CONSTRAINT "saas_route_modules_module_code_fkey" FOREIGN KEY ("module_code") REFERENCES "saas_modules"("code") ON DELETE CASCADE ON UPDATE CASCADE;

